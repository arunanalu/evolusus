-- Executar como ADMIN ou EVOLUSUS_STG. Tabela de staging segura para CSV CNES PF.
-- Códigos são texto para preservar zeros à esquerda e valores alfanuméricos.
CREATE TABLE EVOLUSUS_STG.CNES_PF_DATA_CORRIGIDA (
  CNES VARCHAR2(4000), CODUFMUN VARCHAR2(4000), REGSAUDE VARCHAR2(4000), MICR_REG VARCHAR2(4000),
  DISTRSAN VARCHAR2(4000), DISTRADM VARCHAR2(4000), TPGESTAO VARCHAR2(4000), PF_PJ VARCHAR2(4000),
  CPF_CNPJ VARCHAR2(4000), NIV_DEP VARCHAR2(4000), CNPJ_MAN VARCHAR2(4000), ESFERA_A VARCHAR2(4000),
  ATIVIDAD VARCHAR2(4000), RETENCAO VARCHAR2(4000), NATUREZA VARCHAR2(4000), CLIENTEL VARCHAR2(4000),
  TP_UNID VARCHAR2(4000), TURNO_AT VARCHAR2(4000), NIV_HIER VARCHAR2(4000), TERCEIRO VARCHAR2(4000),
  CPF_PROF VARCHAR2(4000), CPFUNICO VARCHAR2(4000), CBO VARCHAR2(20), CBOUNICO VARCHAR2(20),
  NOMEPROF VARCHAR2(4000), CNS_PROF VARCHAR2(4000), CONSELHO VARCHAR2(20), REGISTRO VARCHAR2(4000),
  VINCULAC VARCHAR2(4000), VINCUL_C VARCHAR2(4000), VINCUL_A VARCHAR2(4000), VINCUL_N VARCHAR2(4000),
  PROF_SUS VARCHAR2(4000), PROFNSUS VARCHAR2(4000), HORAOUTR VARCHAR2(4000), HORAHOSP VARCHAR2(4000),
  HORA_AMB VARCHAR2(4000), COMPETEN VARCHAR2(4000), UFMUNRES VARCHAR2(4000), NAT_JUR VARCHAR2(4000),
  ANO_COMPETENCIA VARCHAR2(4000), MES_COMPETENCIA VARCHAR2(4000), SHA256_ORIGEM VARCHAR2(4000),
  ARQUIVO_ORIGEM VARCHAR2(4000), VERSAO_CONVERSOR VARCHAR2(4000), LAYOUT_SHA256 VARCHAR2(4000),
  CARGADO_EM_UTC TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL
);

COMMENT ON TABLE EVOLUSUS_STG.CNES_PF_DATA_CORRIGIDA IS
  'Carga corrigida CNES PF/RJ/2025; códigos preservados como texto para evitar rejeições de inferência.';
